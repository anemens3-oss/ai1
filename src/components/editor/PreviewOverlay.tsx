import { useEffect, useMemo, useState } from 'react';
import type { DeviceMode, GeneratedSite } from '../../types/design';
import { compileDocument, DEVICE_WIDTHS } from '../../lib/codegen';
import { exportSiteZip, downloadBlob, slugify } from '../../lib/exporter';
import { useEditor } from '../../store/editor';

// Sandboxed live preview of the generated site + ZIP export.

function buildSrcDoc(site: GeneratedSite | null, fallbackHtml: string, fallbackCss: string, fallbackJs: string): string {
  if (site && site.engine === 'deepseek') {
    return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${site.css}</style></head><body>${site.html}<script>${site.js}<\/script></body></html>`;
  }
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${fallbackCss}</style></head><body><div class="site-root">${fallbackHtml}</div><script>${fallbackJs}<\/script></body></html>`;
}

export default function PreviewOverlay({ onClose }: { onClose: () => void }) {
  const { doc, generated } = useEditor();
  const [device, setDevice] = useState<DeviceMode>('desktop');
  const [reloadKey, setReloadKey] = useState(0);
  const [exporting, setExporting] = useState(false);

  const srcDoc = useMemo(() => {
    if (!doc) return '';
    const c = compileDocument(doc, { engine: generated?.engine ?? 'local' });
    return buildSrcDoc(generated, c.html, c.css, c.js);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [doc, generated, reloadKey]);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);

  if (!doc) return null;

  async function doExport() {
    if (!doc) return;
    setExporting(true);
    try {
      const blob = await exportSiteZip(doc, generated);
      downloadBlob(blob, `${slugify(doc.name)}.zip`);
    } finally {
      setExporting(false);
    }
  }

  const width = DEVICE_WIDTHS[device];

  return (
    <div className="preview-overlay">
      <div className="preview-bar">
        <div className="preview-bar-left">
          <strong>Live Preview</strong>
          <span className={`chip ${generated?.engine === 'deepseek' ? 'ok' : ''}`}>
            <span className="badge-dot" style={{ background: generated?.engine === 'deepseek' ? 'var(--success)' : 'var(--accent-2)' }} />
            {generated
              ? generated.engine === 'deepseek'
                ? `Generated by DeepSeek ${generated.model ?? ''}`
                : 'Generated by SITECRAFT Local Engine'
              : 'Direct render of the design document'}
          </span>
        </div>
        <div className="preview-bar-center">
          {(['desktop', 'tablet', 'mobile'] as DeviceMode[]).map((d) => (
            <button key={d} className={`pv-device ${device === d ? 'active' : ''}`} onClick={() => setDevice(d)}>
              {d === 'desktop' ? '🖥' : d === 'tablet' ? '📱' : '📲'} {d}
            </button>
          ))}
        </div>
        <div className="preview-bar-right">
          <button className="btn btn-ghost btn-sm" onClick={() => setReloadKey((k) => k + 1)}>↻ Reload</button>
          <button className="btn btn-primary btn-sm" disabled={exporting} onClick={() => void doExport()}>
            {exporting ? 'Packing…' : '⬇ Export ZIP'}
          </button>
          <button className="btn btn-ghost btn-sm" onClick={onClose}>✕ Back to editor</button>
        </div>
      </div>
      <div className="preview-stage">
        <div className="preview-frame" style={{ width, maxWidth: '96vw' }}>
          <iframe
            key={`${device}-${reloadKey}`}
            title="Generated website preview"
            sandbox="allow-scripts"
            srcDoc={srcDoc}
            style={{ width: '100%', height: '100%', border: 'none', background: '#fff' }}
          />
        </div>
      </div>
    </div>
  );
}
